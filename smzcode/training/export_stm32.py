"""Export the selected FP32 model for the Keil firmware."""

import argparse
import json
from pathlib import Path
import zlib

import numpy as np


SHAPES = {
    "scaler_mean": (5,), "scaler_std": (5,), "net.0.weight": (184, 40),
    "net.0.bias": (184,), "net.2.weight": (16, 184), "net.2.bias": (16,),
}
INPUTS = ["Fz_total_cal", "JJJ1_1_raw", "JJJ1_2_raw", "JJJ2_1_raw", "JJJ2_2_raw"]


def literals(array):
    values = [f"{x:.9e}f" for x in np.asarray(array, dtype=np.float32).ravel()]
    return "\n".join("        " + ", ".join(values[i:i + 6]) + "," for i in range(0, len(values), 6))


def main():
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-dir", type=Path, default=Path(__file__).with_name("trained_models"))
    args = parser.parse_args()
    path = args.model_dir / "pyramidmlp.npz"
    summary = json.loads((args.model_dir / "training_summary.json").read_text(encoding="utf-8"))
    calibration = summary["calibration"]
    coefficients = np.asarray(calibration["coefficients"], dtype="<f4")
    if (coefficients.shape != (3,) or not np.isfinite(coefficients).all()
            or calibration["reference_sign"] != "compression_negative"):
        parser.error("需要压缩为负的联合标定")
    tag = zlib.crc32(coefficients.tobytes())
    if not path.is_file():
        parser.error(f"缺少入选模型 {path}，请先运行 training.train")
    with np.load(path, allow_pickle=False) as data:
        if (data["input_columns"].tolist() != INPUTS or data["h_ms"].tolist() != list(range(16))
                or data["scales"].tolist() != [2, 4, 8, 16]):
            parser.error(f"输入、预测时距或特征窗口与板端不一致：{path}")
        seed = data["seed"].item()
        if seed != summary["selected_seed"]:
            parser.error("模型权重与训练摘要的种子不一致")
        arrays = [np.asarray(data[key], dtype="<f4") for key in SHAPES]
        for (key, shape), array in zip(SHAPES.items(), arrays):
            if array.shape != shape or not np.isfinite(array).all():
                parser.error(f"权重无效：{path.name} {key}")
            tag = zlib.crc32(array.tobytes(), tag)
        if np.any(arrays[1] <= 0):
            parser.error(f"标准差无效：{path.name}")
    lines = ["/* Generated by smzcode/training/export_stm32.py. */",
             f"#define FOOT_MODEL_TAG 0x{tag:08X}UL",
             "static const float model_calibration[3] = {", literals(coefficients), "};",
             "static const FootModel foot_model = {"]
    for array in arrays:
        lines.extend(["    {", literals(array), "    },"])
    lines.append("};")
    (root / "Core/Src/foot_model_weights.inc").write_text("\n".join(lines) + "\n", encoding="ascii")
    metadata = {"model_tag": tag, "selected_seed": seed, "calibration": calibration}
    (root / "smzcode/controller/config/board_model.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"STM32 model 0x{tag:08X}")


if __name__ == "__main__":
    main()
